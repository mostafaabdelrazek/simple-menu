/** Copy for the visitor's language, falling back to English key by key. */
export function landingCopy(locale) {
    return merge(LANDING_COPY[locale] ?? {}, LANDING_COPY.en);
}

function merge(primary, fallback) {
    const result = { ...fallback };

    for (const [key, value] of Object.entries(primary)) {
        const base = fallback[key];

        if (value !== null && typeof value === 'object' && !Array.isArray(value) && base && typeof base === 'object') {
            result[key] = merge(value, base);
        } else {
            result[key] = value;
        }
    }

    return result;
}
